// Turns the token model into one file per platform. Emitters are pure: model in, text out.

import {
  type ColorToken,
  INPUT_MODES,
  type Model,
  type Rgba,
  type SizeToken,
  type Typography,
  type Value,
  type ValueToken,
} from "./model.ts";

const HEADER = "Generated by tools/design-build from design/tokens. Do not edit.";

const GENERIC_FONT_FAMILIES = new Set(["serif", "sans-serif", "monospace", "system-ui"]);

function hex({ r, g, b }: Rgba): string {
  return `#${[r, g, b].map((channel) => channel.toString(16).padStart(2, "0")).join("")}`;
}

function kebab(path: string[]): string {
  return path.join("-");
}

function camel(text: string): string {
  return text.replace(/-([a-z0-9])/g, (_, letter: string) => letter.toUpperCase());
}

// ---------------------------------------------------------------- CSS

function cssColor(color: Rgba): string {
  return color.a === 1 ? hex(color) : `rgb(${color.r} ${color.g} ${color.b} / ${color.a})`;
}

function cssValue(value: Value): string {
  switch (value.kind) {
    case "dimension":
      return `${value.px}px`;
    case "duration":
      return `${value.ms}ms`;
    case "number":
    case "fontWeight":
      return String(value.value);
    case "fontFamily":
      return value.families
        .map((family) => (GENERIC_FONT_FAMILIES.has(family) ? family : JSON.stringify(family)))
        .join(", ");
    case "cubicBezier":
      return `cubic-bezier(${value.points.join(", ")})`;
    case "shadow": {
      const { offsetX, offsetY, blur, spread, color } = value.shadow;
      return `${offsetX}px ${offsetY}px ${blur}px ${spread}px ${cssColor(color)}`;
    }
    case "typography":
      throw new Error("a typography token has no single CSS value; see typographyVariables");
  }
}

/** A text style becomes one custom property per part, since CSS has no single value for it. */
function typographyVariables(token: ValueToken, style: Typography): [string, string][] {
  const name = valueVariable(token);
  return [
    [`${name}-size`, `${style.sizePx}px`],
    [`${name}-weight`, String(style.weight)],
    [`${name}-line-height`, String(style.lineHeight)],
    [`${name}-letter-spacing`, `${style.letterSpacingPx}px`],
  ];
}

function sizeVariable(token: SizeToken): string {
  return `--acme-size-${kebab(token.path)}`;
}

function colorVariable(token: ColorToken): string {
  return `--acme-color-${kebab(token.path)}`;
}

function valueVariable(token: ValueToken): string {
  return `--acme-${kebab(token.path)}`;
}

/**
 * Custom properties for every token. Colors follow the color scheme through `light-dark()`, and
 * sizes follow the input device through a media query.
 */
export function emitCss(model: Model): string {
  const lines = [`/* ${HEADER} */`, "", ":root {", "  color-scheme: light dark;", ""];
  for (const token of model.colors) {
    const [light, dark] = [cssColor(token.light), cssColor(token.dark)];
    const value = light === dark ? light : `light-dark(${light}, ${dark})`;
    lines.push(`  ${colorVariable(token)}: ${value};`);
  }
  lines.push("");
  for (const token of model.values) {
    if (token.value.kind === "typography") {
      for (const [name, value] of typographyVariables(token, token.value.typography)) {
        lines.push(`  ${name}: ${value};`);
      }
    } else {
      lines.push(`  ${valueVariable(token)}: ${cssValue(token.value)};`);
    }
  }
  if (model.sizes.length > 0) lines.push("");
  for (const token of model.sizes) {
    lines.push(`  ${sizeVariable(token)}: ${token.pointer}px;`);
  }
  lines.push("}", "");
  if (model.sizes.length > 0) {
    lines.push(
      "/* Fingers need larger controls than a mouse. This asks about the primary input, not the",
      "   screen width: a small window on a laptop keeps the pointer sizes. */",
      "@media (pointer: coarse) {",
      "  :root {",
    );
    for (const token of model.sizes) {
      lines.push(`    ${sizeVariable(token)}: ${token.touch}px;`);
    }
    lines.push("  }", "}", "");
  }
  lines.push(
    "/* Set data-theme on the root element to override the system color scheme. */",
    ':root[data-theme="light"] {',
    "  color-scheme: light;",
    "}",
    "",
    ':root[data-theme="dark"] {',
    "  color-scheme: dark;",
    "}",
    "",
  );
  return lines.join("\n");
}

/** Where a token group lands in Tailwind's theme. Groups that are not listed get no utility. */
const TAILWIND_NAMESPACES: [prefix: string[], namespace: string][] = [
  [["radius"], "radius"],
  [["font", "family"], "font"],
  [["font", "weight"], "font-weight"],
  [["font", "line-height"], "leading"],
  [["motion", "easing"], "ease"],
  [["shadow"], "shadow"],
];

/**
 * A Tailwind v4 theme that points at the custom properties from `emitCss`. Every key carries an
 * `acme` prefix (`bg-acme-overlay-surface`, `rounded-acme-lg`), so the theme cannot collide with
 * Tailwind's defaults or with a component library's own theme. Spacing is left out: the tokens
 * use the same 4px grid as Tailwind's default spacing scale.
 */
export function emitTailwind(model: Model): string {
  const lines = [`/* ${HEADER} */`, "", "@theme inline {"];
  for (const token of model.colors) {
    lines.push(`  --color-acme-${kebab(token.path)}: var(${colorVariable(token)});`);
  }
  for (const [prefix, namespace] of TAILWIND_NAMESPACES) {
    const tokens = model.values.filter(
      (token) =>
        token.path.length === prefix.length + 1 &&
        prefix.every((segment, index) => token.path[index] === segment),
    );
    if (tokens.length > 0) lines.push("");
    for (const token of tokens) {
      lines.push(`  --${namespace}-acme-${token.path.at(-1)}: var(${valueVariable(token)});`);
    }
  }
  // `text-acme-body` sets size, line height, weight and tracking together. Raw font sizes get no
  // utility on purpose: a screen picks a text role, not a size.
  const styles = model.values.filter((token) => token.value.kind === "typography");
  if (styles.length > 0) lines.push("");
  for (const token of styles) {
    const key = `--text-acme-${token.path.at(-1)}`;
    const part = (name: string) => `var(${valueVariable(token)}-${name})`;
    lines.push(
      `  ${key}: ${part("size")};`,
      `  ${key}--line-height: ${part("line-height")};`,
      `  ${key}--font-weight: ${part("weight")};`,
      `  ${key}--letter-spacing: ${part("letter-spacing")};`,
    );
  }
  // Sizes join the spacing scale, so `h-acme-control-md` and `min-w-acme-target-min` both work.
  if (model.sizes.length > 0) lines.push("");
  for (const token of model.sizes) {
    lines.push(`  --spacing-acme-${kebab(token.path)}: var(${sizeVariable(token)});`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

// ---------------------------------------------------------------- TypeScript

/** A color string that both the web and React Native accept. */
function jsColor(color: Rgba): string {
  return color.a === 1 ? hex(color) : `rgba(${color.r}, ${color.g}, ${color.b}, ${color.a})`;
}

function jsValue(value: Value): unknown {
  switch (value.kind) {
    case "dimension":
      return value.px;
    case "duration":
      return value.ms;
    case "number":
    case "fontWeight":
      return value.value;
    case "fontFamily":
      return value.families;
    case "cubicBezier":
      return value.points;
    case "shadow":
      return { ...value.shadow, color: jsColor(value.shadow.color) };
    case "typography": {
      // The shape React Native's text style takes: line height in pixels, no font family (an
      // app can only name a family it has loaded).
      const { sizePx, weight, lineHeight, letterSpacingPx } = value.typography;
      return {
        fontSize: sizePx,
        lineHeight: Math.round(sizePx * lineHeight),
        fontWeight: weight,
        letterSpacing: letterSpacingPx,
      };
    }
  }
}

type Tree = { [key: string]: Tree | unknown };

/** Lengths are in logical pixels and durations in milliseconds. */
export function emitTypeScript(model: Model): string {
  const colors = (mode: "light" | "dark") =>
    Object.fromEntries(
      model.colors.map((token) => [camel(kebab(token.path)), jsColor(token[mode])]),
    );

  const groups: Tree = {};
  for (const token of model.values) {
    let node = groups;
    for (const segment of token.path.slice(0, -1)) {
      const key = camel(segment);
      node[key] ??= {};
      node = node[key] as Tree;
    }
    node[camel(token.path.at(-1) as string)] = jsValue(token.value);
  }

  const lines = [
    `// ${HEADER}`,
    "// Lengths are in logical pixels and durations in milliseconds.",
    "",
    `export const colors = ${JSON.stringify({ light: colors("light"), dark: colors("dark") }, null, 2)} as const;`,
  ];
  for (const [name, group] of Object.entries(groups)) {
    lines.push("", `export const ${name} = ${JSON.stringify(group, null, 2)} as const;`);
  }
  if (model.sizes.length > 0) {
    const sizes = Object.fromEntries(
      INPUT_MODES.map((mode) => [
        mode,
        Object.fromEntries(model.sizes.map((token) => [camel(kebab(token.path)), token[mode]])),
      ]),
    );
    lines.push(
      "",
      "/** Control sizes by input device: `pointer` for a mouse, `touch` for fingers. */",
      `export const size = ${JSON.stringify(sizes, null, 2)} as const;`,
    );
  }
  lines.push("");
  return lines.join("\n");
}

// ---------------------------------------------------------------- Kotlin

function float(value: number): string {
  return Number.isInteger(value) ? `${value}.0` : String(value);
}

function pascal(text: string): string {
  const name = camel(text);
  return name.charAt(0).toUpperCase() + name.slice(1);
}

function kotlinFloat(value: number): string {
  return `${float(value)}f`;
}

function kotlinColor({ r, g, b, a }: Rgba): string {
  const channels = [Math.round(a * 255), r, g, b];
  return `Color(0x${channels.map((channel) => channel.toString(16).padStart(2, "0").toUpperCase()).join("")})`;
}

/** Type sizes are in sp, so they follow the system's text size setting. Everything else is dp. */
function kotlinValue(token: ValueToken): [type: string, value: string] {
  const { value } = token;
  switch (value.kind) {
    case "dimension":
      return token.path[0] === "font" ? ["TextUnit", `${value.px}.sp`] : ["Dp", `${value.px}.dp`];
    case "duration":
      return ["Int", String(value.ms)];
    case "number":
      return ["Float", kotlinFloat(value.value)];
    case "fontWeight":
      return ["FontWeight", `FontWeight(${value.value})`];
    case "fontFamily":
      return [
        "List<String>",
        `listOf(${value.families.map((family) => JSON.stringify(family)).join(", ")})`,
      ];
    case "cubicBezier":
      return ["Easing", `CubicBezierEasing(${value.points.map(kotlinFloat).join(", ")})`];
    case "shadow": {
      const { color, offsetX, offsetY, blur, spread } = value.shadow;
      return [
        "ShadowToken",
        `ShadowToken(color = ${kotlinColor(color)}, offsetX = ${offsetX}.dp, offsetY = ${offsetY}.dp, ` +
          `blur = ${blur}.dp, spread = ${spread}.dp)`,
      ];
    }
    case "typography": {
      const { sizePx, weight, lineHeight, letterSpacingPx } = value.typography;
      return [
        "TextStyle",
        `TextStyle(fontSize = ${sizePx}.sp, lineHeight = ${Math.round(sizePx * lineHeight)}.sp, ` +
          `fontWeight = FontWeight(${weight}), letterSpacing = ${letterSpacingPx}.sp)`,
      ];
    }
  }
}

/**
 * Compose types, in one object per token group: `Space.s4`, `Radius.md`, `Typography.body`. A
 * name that starts with a digit gets the first letter of its group in front. Colors are one
 * object per mode behind an interface, not a class with a constructor: a constructor with this
 * many color parameters does not fit in a JVM method.
 */
export function emitKotlin(model: Model, packageName: string): string {
  const property = (path: string[]) => camel(kebab(path));
  const lines = [
    `// ${HEADER}`,
    "",
    `package ${packageName}`,
    "",
    "import androidx.compose.animation.core.CubicBezierEasing",
    "import androidx.compose.animation.core.Easing",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.text.TextStyle",
    "import androidx.compose.ui.text.font.FontWeight",
    "import androidx.compose.ui.unit.Dp",
    "import androidx.compose.ui.unit.TextUnit",
    "import androidx.compose.ui.unit.dp",
    "import androidx.compose.ui.unit.sp",
    "",
    "/** Every color token, for one mode. */",
    "interface Colors {",
  ];
  for (const token of model.colors) {
    if (token.description) lines.push(`    /** ${token.description} */`);
    lines.push(`    val ${property(token.path)}: Color`);
  }
  lines.push(
    "",
    "    /** Every color with its token name, in token order. For screens that list the colors. */",
    "    fun entries(): List<Pair<String, Color>> = listOf(",
  );
  for (const token of model.colors) {
    lines.push(`        "${kebab(token.path)}" to ${property(token.path)},`);
  }
  lines.push("    )", "}");
  for (const mode of ["light", "dark"] as const) {
    lines.push("", `object ${pascal(mode)}Colors : Colors {`);
    for (const token of model.colors) {
      lines.push(`    override val ${property(token.path)} = ${kotlinColor(token[mode])}`);
    }
    lines.push("}");
  }

  const groups = new Map<string, ValueToken[]>();
  for (const token of model.values) {
    const group = token.path[0] as string;
    groups.set(group, [...(groups.get(group) ?? []), token]);
  }
  for (const [group, tokens] of groups) {
    lines.push("", `object ${pascal(group)} {`);
    for (const token of tokens) {
      const name = property(token.path.slice(1));
      const [type, value] = kotlinValue(token);
      if (token.description) lines.push(`    /** ${token.description} */`);
      lines.push(
        `    val ${/^[0-9]/.test(name) ? group.charAt(0) + name : name}: ${type} = ${value}`,
      );
    }
    lines.push("}");
  }

  if (model.sizes.length > 0) {
    lines.push("", "/** Control sizes, for one input device. */", "class Sizes(");
    for (const token of model.sizes) {
      if (token.description) lines.push(`    /** ${token.description} */`);
      lines.push(`    val ${property(token.path)}: Dp,`);
    }
    lines.push(")");
    for (const mode of INPUT_MODES) {
      lines.push("", `val ${pascal(mode)}Sizes = Sizes(`);
      for (const token of model.sizes) {
        lines.push(`    ${property(token.path)} = ${token[mode]}.dp,`);
      }
      lines.push(")");
    }
  }
  lines.push("");
  return lines.join("\n");
}

// ---------------------------------------------------------------- Rust

function rustColor(color: Rgba): string {
  return `Color::rgba(${color.r}, ${color.g}, ${color.b}, ${float(color.a)})`;
}

function rustConst(token: ValueToken): string {
  const name = token.path.join("_").replaceAll("-", "_").toUpperCase();
  const { value } = token;
  switch (value.kind) {
    case "dimension":
      return `pub const ${name}: f32 = ${float(value.px)};`;
    case "duration":
      return `pub const ${name}: Duration = Duration::from_millis(${value.ms});`;
    case "number":
      return `pub const ${name}: f32 = ${float(value.value)};`;
    case "fontWeight":
      return `pub const ${name}: f32 = ${float(value.value)};`;
    case "fontFamily":
      return `pub const ${name}: &[&str] = &[${value.families.map((family) => JSON.stringify(family)).join(", ")}];`;
    case "cubicBezier":
      return `pub const ${name}: CubicBezier = [${value.points.map(float).join(", ")}];`;
    case "shadow": {
      const { color, offsetX, offsetY, blur, spread } = value.shadow;
      return (
        `pub const ${name}: Shadow = Shadow { color: ${rustColor(color)}, ` +
        `offset_x: ${float(offsetX)}, offset_y: ${float(offsetY)}, ` +
        `blur: ${float(blur)}, spread: ${float(spread)} };`
      );
    }
    case "typography": {
      const { sizePx, weight, lineHeight, letterSpacingPx } = value.typography;
      return (
        `pub const ${name}: Typography = Typography { size: ${float(sizePx)}, ` +
        `weight: ${float(weight)}, line_height: ${float(lineHeight)}, ` +
        `letter_spacing: ${float(letterSpacingPx)} };`
      );
    }
  }
}

/**
 * Plain constants with no UI-framework types, so the crate stays dependency-free. The module is
 * declared with `#[rustfmt::skip]`, so the layout here does not have to match rustfmt's.
 */
export function emitRust(model: Model): string {
  const field = (token: { path: string[] }) => token.path.join("_").replaceAll("-", "_");
  const lines = [
    `// ${HEADER}`,
    "",
    "use std::time::Duration;",
    "",
    "use crate::{Color, CubicBezier, Shadow, Typography};",
    "",
    "/// Every color token, for one mode.",
    "#[derive(Debug, Clone, Copy, PartialEq)]",
    "pub struct Colors {",
  ];
  for (const token of model.colors) {
    if (token.description) lines.push(`    /// ${token.description}`);
    lines.push(`    pub ${field(token)}: Color,`);
  }
  lines.push(
    "}",
    "",
    "impl Colors {",
    "    /// Every color with its token name, in token order. For screens that list the colors.",
    `    pub const fn entries(&self) -> [(&'static str, Color); ${model.colors.length}] {`,
    "        [",
  );
  for (const token of model.colors) {
    lines.push(`            ("${kebab(token.path)}", self.${field(token)}),`);
  }
  lines.push("        ]", "    }", "}");
  for (const mode of ["light", "dark"] as const) {
    lines.push("", `pub const ${mode.toUpperCase()}: Colors = Colors {`);
    for (const token of model.colors) {
      lines.push(`    ${field(token)}: ${rustColor(token[mode])},`);
    }
    lines.push("};");
  }
  let group: string | undefined;
  for (const token of model.values) {
    const tokenGroup = token.path.slice(0, -1).join(".");
    if (tokenGroup !== group) lines.push("");
    group = tokenGroup;
    if (token.description) lines.push(`/// ${token.description}`);
    lines.push(rustConst(token));
  }
  if (model.sizes.length > 0) {
    lines.push(
      "",
      "/// Control sizes, for one input device.",
      "#[derive(Debug, Clone, Copy, PartialEq)]",
      "pub struct Sizes {",
    );
    for (const token of model.sizes) {
      if (token.description) lines.push(`    /// ${token.description}`);
      lines.push(`    pub ${field(token)}: f32,`);
    }
    lines.push("}");
    for (const mode of INPUT_MODES) {
      lines.push("", `pub const ${mode.toUpperCase()}: Sizes = Sizes {`);
      for (const token of model.sizes) {
        lines.push(`    ${field(token)}: ${float(token[mode])},`);
      }
      lines.push("};");
    }
  }
  lines.push("");
  return lines.join("\n");
}
