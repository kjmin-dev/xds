// Turns the token model into one file per platform. Emitters are pure: model in, text out.

import { ICON_GRID, ICON_STROKE, type Icon } from "./icons.ts";
import {
  type ColorToken,
  INPUT_MODES,
  MODES,
  type Model,
  type Rgba,
  type SizeToken,
  TokenError,
  type Typography,
  type Value,
  type ValueToken,
} from "./model.ts";

const HEADER = "Generated by tools/design-build from design/tokens. Do not edit.";

const GENERIC_FONT_FAMILIES = new Set(["serif", "sans-serif", "monospace", "system-ui"]);

function hex({ r, g, b }: Rgba): string {
  return `#${[r, g, b].map((channel) => channel.toString(16).padStart(2, "0")).join("")}`;
}

function kebab(path: string[]): string {
  return path.join("-");
}

function camel(text: string): string {
  // A half step such as `0-5` keeps its separator, as `0_5`: without one it would read as 05.
  return text
    .replace(/(\d)-(\d)/g, "$1_$2")
    .replace(/-([a-z0-9])/g, (_, letter: string) => letter.toUpperCase());
}

// ---------------------------------------------------------------- CSS

function cssColor(color: Rgba): string {
  return color.a === 1 ? hex(color) : `rgb(${color.r} ${color.g} ${color.b} / ${color.a})`;
}

function cssValue(value: Value): string {
  switch (value.kind) {
    case "dimension":
      return `${value.px}px`;
    case "duration":
      return `${value.ms}ms`;
    case "number":
    case "fontWeight":
      return String(value.value);
    case "fontFamily":
      return value.families
        .map((family) => (GENERIC_FONT_FAMILIES.has(family) ? family : JSON.stringify(family)))
        .join(", ");
    case "cubicBezier":
      return `cubic-bezier(${value.points.join(", ")})`;
    case "shadow": {
      const { offsetX, offsetY, blur, spread, color } = value.shadow;
      return `${offsetX}px ${offsetY}px ${blur}px ${spread}px ${cssColor(color)}`;
    }
    case "typography":
      throw new Error("a typography token has no single CSS value; see typographyVariables");
  }
}

/** A text style becomes one custom property per part, since CSS has no single value for it. */
function typographyVariables(token: ValueToken, style: Typography): [string, string][] {
  const name = valueVariable(token);
  return [
    [`${name}-size`, `${style.sizePx}px`],
    [`${name}-weight`, String(style.weight)],
    [`${name}-line-height`, String(style.lineHeight)],
    [`${name}-letter-spacing`, `${style.letterSpacingPx}px`],
  ];
}

function sizeVariable(token: SizeToken): string {
  return `--acme-size-${kebab(token.path)}`;
}

function colorVariable(token: ColorToken): string {
  return `--acme-color-${kebab(token.path)}`;
}

function valueVariable(token: ValueToken): string {
  return `--acme-${kebab(token.path)}`;
}

/** Every token as a custom property: colors and the other values, then sizes per input. */
function declarations(model: Model) {
  const shared: [string, string][] = [];
  for (const token of model.colors) {
    const [light, dark] = [cssColor(token.light), cssColor(token.dark)];
    shared.push([colorVariable(token), light === dark ? light : `light-dark(${light}, ${dark})`]);
  }
  const values: [string, string][] = [];
  for (const token of model.values) {
    if (token.value.kind === "typography") {
      values.push(...typographyVariables(token, token.value.typography));
    } else {
      values.push([valueVariable(token), cssValue(token.value)]);
    }
  }
  const pointer = model.sizes.map((token): [string, string] => [
    sizeVariable(token),
    `${token.pointer}px`,
  ]);
  const touch = model.sizes.map((token): [string, string] => [
    sizeVariable(token),
    `${token.touch}px`,
  ]);
  return { colors: shared, values, pointer, touch };
}

const TOUCH_COMMENT = [
  "/* Fingers need larger controls than a mouse. This asks about the primary input, not the",
  "   screen width: a small window on a laptop keeps the pointer sizes. */",
];

/**
 * Custom properties for every token. Colors follow the color scheme through `light-dark()`, and
 * sizes follow the input device through a media query.
 */
export function emitCss(model: Model): string {
  const { colors, values, pointer, touch } = declarations(model);
  const block = (list: [string, string][], indent: string) =>
    list.map(([name, value]) => `${indent}${name}: ${value};`);
  const lines = [`/* ${HEADER} */`, "", ":root {", "  color-scheme: light dark;", ""];
  lines.push(...block(colors, "  "), "", ...block(values, "  "));
  if (pointer.length > 0) lines.push("", ...block(pointer, "  "));
  lines.push("}", "");
  if (touch.length > 0) {
    lines.push(...TOUCH_COMMENT, "@media (pointer: coarse) {", "  :root {");
    lines.push(...block(touch, "    "), "  }", "}", "");
  }
  lines.push(
    "/* Set data-theme to override the system color scheme, on the root element for the whole",
    "   page or on any element for what is inside it. */",
    '[data-theme="light"] {',
    "  color-scheme: light;",
    "}",
    "",
    '[data-theme="dark"] {',
    "  color-scheme: dark;",
    "}",
    "",
  );
  return lines.join("\n");
}

/**
 * A theme as a stylesheet of its own: every token's value, on the elements that name the theme
 * with `data-acme-theme="<name>"`, which may be the root element or any element inside. Every
 * token is written, not only those that differ from the default theme, so a theme inside another
 * takes nothing from the outer one. `layer` puts the rules in a cascade layer; `prefix` replaces
 * `acme` in the names, for a library published under another name.
 */
export function emitThemeCss(
  model: Model,
  options: { name: string; source: string; layer?: string; prefix?: string },
): string {
  if (!/^[a-z][a-z0-9-]*$/.test(options.name)) {
    throw new TokenError(
      `a theme name is lowercase letters, digits and hyphens: "${options.name}"`,
    );
  }
  const prefix = options.prefix ?? "acme";
  const rename = (text: string) => text.replace(/^--acme-/, `--${prefix}-`);
  const { colors, values, pointer, touch } = declarations(model);
  const outer = options.layer ? "  " : "";
  const selector = (indent: string) => [
    `${indent}:root[data-${prefix}-theme="${options.name}"],`,
    `${indent}[data-${prefix}-theme="${options.name}"] {`,
  ];
  const block = (list: [string, string][], indent: string) =>
    list.map(([name, value]) => `${indent}${rename(name)}: ${value};`);
  const body = [...selector(outer), ...block([...colors, ...values, ...pointer], `${outer}  `)];
  body.push(`${outer}}`);
  if (touch.length > 0) {
    body.push("", ...TOUCH_COMMENT.map((line) => `${outer}${line}`));
    body.push(`${outer}@media (pointer: coarse) {`, ...selector(`${outer}  `));
    body.push(...block(touch, `${outer}    `), `${outer}  }`, `${outer}}`);
  }
  const lines = [`/* Generated by xds from ${options.source}. Do not edit. */`, ""];
  if (options.layer) lines.push(`@layer ${options.layer} {`, ...body, "}", "");
  else lines.push(...body, "");
  return lines.join("\n");
}

/** Where a token group lands in Tailwind's theme. Groups that are not listed get no utility. */
const TAILWIND_NAMESPACES: [prefix: string[], namespace: string][] = [
  [["radius"], "radius"],
  [["font", "family"], "font"],
  [["font", "weight"], "font-weight"],
  [["font", "line-height"], "leading"],
  [["motion", "easing"], "ease"],
  [["shadow"], "shadow"],
];

/**
 * A Tailwind v4 theme that points at the custom properties from `emitCss`. Every key carries an
 * `acme` prefix (`bg-acme-overlay-surface`, `rounded-acme-lg`), so the theme cannot collide with
 * Tailwind's defaults or with a component library's own theme. Spacing is left out: the tokens
 * use the same 4px grid as Tailwind's default spacing scale.
 */
export function emitTailwind(model: Model): string {
  const lines = [`/* ${HEADER} */`, "", "@theme inline {"];
  for (const token of model.colors) {
    lines.push(`  --color-acme-${kebab(token.path)}: var(${colorVariable(token)});`);
  }
  for (const [prefix, namespace] of TAILWIND_NAMESPACES) {
    const tokens = model.values.filter(
      (token) =>
        token.path.length === prefix.length + 1 &&
        prefix.every((segment, index) => token.path[index] === segment),
    );
    if (tokens.length > 0) lines.push("");
    for (const token of tokens) {
      lines.push(`  --${namespace}-acme-${token.path.at(-1)}: var(${valueVariable(token)});`);
    }
  }
  // `text-acme-body` sets size, line height, weight and tracking together. Raw font sizes get no
  // utility on purpose: a screen picks a text role, not a size.
  const styles = model.values.filter((token) => token.value.kind === "typography");
  if (styles.length > 0) lines.push("");
  for (const token of styles) {
    const key = `--text-acme-${token.path.at(-1)}`;
    const part = (name: string) => `var(${valueVariable(token)}-${name})`;
    lines.push(
      `  ${key}: ${part("size")};`,
      `  ${key}--line-height: ${part("line-height")};`,
      `  ${key}--font-weight: ${part("weight")};`,
      `  ${key}--letter-spacing: ${part("letter-spacing")};`,
    );
  }
  // Sizes join the spacing scale, so `h-acme-control-md` and `min-w-acme-target-min` both work.
  if (model.sizes.length > 0) lines.push("");
  for (const token of model.sizes) {
    lines.push(`  --spacing-acme-${kebab(token.path)}: var(${sizeVariable(token)});`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

// ---------------------------------------------------------------- TypeScript

/** A color string that both the web and React Native accept. */
function jsColor(color: Rgba): string {
  return color.a === 1 ? hex(color) : `rgba(${color.r}, ${color.g}, ${color.b}, ${color.a})`;
}

function jsValue(value: Value): unknown {
  switch (value.kind) {
    case "dimension":
      return value.px;
    case "duration":
      return value.ms;
    case "number":
    case "fontWeight":
      return value.value;
    case "fontFamily":
      return value.families;
    case "cubicBezier":
      return value.points;
    case "shadow":
      return { ...value.shadow, color: jsColor(value.shadow.color) };
    case "typography": {
      // The shape React Native's text style takes: line height in pixels, no font family (an
      // app can only name a family it has loaded).
      const { sizePx, weight, lineHeight, letterSpacingPx } = value.typography;
      return {
        fontSize: sizePx,
        lineHeight: Math.round(sizePx * lineHeight),
        fontWeight: weight,
        letterSpacing: letterSpacingPx,
      };
    }
  }
}

type Tree = { [key: string]: unknown };

/** Lengths are in logical pixels and durations in milliseconds. */
export function emitTypeScript(model: Model): string {
  const colors = (mode: "light" | "dark") =>
    Object.fromEntries(
      model.colors.map((token) => [camel(kebab(token.path)), jsColor(token[mode])]),
    );

  const groups: Tree = {};
  for (const token of model.values) {
    let node = groups;
    for (const segment of token.path.slice(0, -1)) {
      const key = camel(segment);
      node[key] ??= {};
      node = node[key] as Tree;
    }
    node[camel(token.path.at(-1) as string)] = jsValue(token.value);
  }

  const lines = [
    `// ${HEADER}`,
    "// Lengths are in logical pixels and durations in milliseconds.",
    "",
    `export const colors = ${JSON.stringify({ light: colors("light"), dark: colors("dark") }, null, 2)} as const;`,
  ];
  for (const [name, group] of Object.entries(groups)) {
    lines.push("", `export const ${name} = ${JSON.stringify(group, null, 2)} as const;`);
  }
  if (model.sizes.length > 0) {
    const sizes = Object.fromEntries(
      INPUT_MODES.map((mode) => [
        mode,
        Object.fromEntries(model.sizes.map((token) => [camel(kebab(token.path)), token[mode]])),
      ]),
    );
    lines.push(
      "",
      "/** Control sizes by input device: `pointer` for a mouse, `touch` for fingers. */",
      `export const size = ${JSON.stringify(sizes, null, 2)} as const;`,
    );
  }
  if (model.icons?.length) {
    const icons = Object.fromEntries(model.icons.map((icon) => [icon.name, icon.paths]));
    lines.push(
      "",
      `/** Icons as SVG path data on a ${ICON_GRID} by ${ICON_GRID} grid, stroked ${ICON_STROKE} wide with round caps and joins. */`,
      `export const icons = ${JSON.stringify(icons, null, 2)} as const;`,
      "",
      "export type IconName = keyof typeof icons;",
    );
  }
  lines.push("");
  return lines.join("\n");
}

// ---------------------------------------------------------------- Kotlin

function float(value: number): string {
  return Number.isInteger(value) ? `${value}.0` : String(value);
}

function pascal(text: string): string {
  const name = camel(text);
  return name.charAt(0).toUpperCase() + name.slice(1);
}

function kotlinFloat(value: number): string {
  return `${float(value)}f`;
}

function argbColor({ r, g, b, a }: Rgba): string {
  const channels = [Math.round(a * 255), r, g, b];
  return `Color(0x${channels.map((channel) => channel.toString(16).padStart(2, "0").toUpperCase()).join("")})`;
}

/** Type sizes are in sp, so they follow the system's text size setting. Everything else is dp. */
function kotlinValue(token: ValueToken): [type: string, value: string] {
  const { value } = token;
  switch (value.kind) {
    case "dimension":
      return token.path[0] === "font" ? ["TextUnit", `${value.px}.sp`] : ["Dp", `${value.px}.dp`];
    case "duration":
      return ["Int", String(value.ms)];
    case "number":
      return ["Float", kotlinFloat(value.value)];
    case "fontWeight":
      return ["FontWeight", `FontWeight(${value.value})`];
    case "fontFamily":
      return [
        "List<String>",
        `listOf(${value.families.map((family) => JSON.stringify(family)).join(", ")})`,
      ];
    case "cubicBezier":
      return ["Easing", `CubicBezierEasing(${value.points.map(kotlinFloat).join(", ")})`];
    case "shadow": {
      const { color, offsetX, offsetY, blur, spread } = value.shadow;
      return [
        "ShadowToken",
        `ShadowToken(color = ${argbColor(color)}, offsetX = ${offsetX}.dp, offsetY = ${offsetY}.dp, ` +
          `blur = ${blur}.dp, spread = ${spread}.dp)`,
      ];
    }
    case "typography": {
      const { sizePx, weight, lineHeight, letterSpacingPx } = value.typography;
      return [
        "TextStyle",
        `TextStyle(fontSize = ${sizePx}.sp, lineHeight = ${Math.round(sizePx * lineHeight)}.sp, ` +
          `fontWeight = FontWeight(${weight}), letterSpacing = ${letterSpacingPx}.sp)`,
      ];
    }
  }
}

/** The token groups of the model's shared values, in token order: `space`, `radius`, … */
function valueGroups(model: Model): Map<string, ValueToken[]> {
  const groups = new Map<string, ValueToken[]>();
  for (const token of model.values) {
    const group = token.path[0] as string;
    groups.set(group, [...(groups.get(group) ?? []), token]);
  }
  return groups;
}

/** A token's name inside its group's class. One that starts with a digit gets the group's initial. */
function kotlinMember(group: string, token: ValueToken): string {
  const name = camel(kebab(token.path.slice(1)));
  return /^[0-9]/.test(name) ? group.charAt(0) + name : name;
}

/** The class that holds one group of shared values: `space` is `SpaceTokens`. */
function kotlinGroupClass(group: string): string {
  return `${pascal(group)}Tokens`;
}

/** The imports a theme value written by `kotlinThemeValue` needs, besides the token types. */
const KOTLIN_VALUE_IMPORTS = [
  "androidx.compose.animation.core.CubicBezierEasing",
  "androidx.compose.ui.graphics.Color",
  "androidx.compose.ui.text.TextStyle",
  "androidx.compose.ui.text.font.FontWeight",
  "androidx.compose.ui.unit.dp",
  "androidx.compose.ui.unit.sp",
];

/** The token types a theme value refers to by name. */
function kotlinTokenTypes(model: Model): string[] {
  const types = ["Colors", "Theme", ...[...valueGroups(model).keys()].map(kotlinGroupClass)];
  if (model.sizes.length > 0) types.push("Sizes");
  if (model.values.some((token) => token.value.kind === "shadow")) types.push("ShadowToken");
  return types.sort();
}

/**
 * A theme as a Kotlin value: `val <name>Theme: Theme = Theme(…)`, with its two color sets as
 * private objects beside it. The token build writes the default theme with it, and
 * `xds export-theme --format compose` a theme file, so both have the same shape.
 */
function kotlinThemeValue(model: Model, name: string, doc: string[]): string[] {
  const property = (path: string[]) => camel(kebab(path));
  const lines = ["/**", ...doc.map((line) => (line ? ` * ${line}` : " *")), " */"];
  lines.push(`val ${name}Theme: Theme = Theme(`);
  lines.push(`    light = ${name}LightColors,`, `    dark = ${name}DarkColors,`);
  if (model.sizes.length > 0) {
    for (const mode of INPUT_MODES) {
      lines.push(`    ${mode} = Sizes(`);
      for (const token of model.sizes) {
        lines.push(`        ${property(token.path)} = ${token[mode]}.dp,`);
      }
      lines.push("    ),");
    }
  }
  for (const [group, tokens] of valueGroups(model)) {
    lines.push(`    ${camel(group)} = ${kotlinGroupClass(group)}(`);
    for (const token of tokens) {
      lines.push(`        ${kotlinMember(group, token)} = ${kotlinValue(token)[1]},`);
    }
    lines.push("    ),");
  }
  lines.push(")");
  for (const mode of MODES) {
    lines.push("", `private object ${name}${pascal(mode)}Colors : Colors {`);
    for (const token of model.colors) {
      lines.push(`    override val ${property(token.path)} = ${argbColor(token[mode])}`);
    }
    lines.push("}");
  }
  return lines;
}

/**
 * Compose types: the tokens of one color mode behind the `Colors` interface, the sizes of one
 * input device in `Sizes`, and one class per group of shared values (`SpaceTokens`,
 * `RadiusTokens`). A `Theme` holds a full set of them, and `DefaultTheme` is the one the token
 * files describe. Components read the theme in effect through one property per group, `Space.s4`
 * or `Typography.body`, which ask the composition, so a theme given at run time reaches them. A
 * name that starts with a digit gets the first letter of its group in front. Colors are behind an
 * interface, not a class with a constructor: a constructor with this many color parameters does
 * not fit in a JVM method.
 */
export function emitKotlin(model: Model, packageName: string): string {
  const property = (path: string[]) => camel(kebab(path));
  const groups = valueGroups(model);
  const lines = [
    `// ${HEADER}`,
    "",
    `package ${packageName}`,
    "",
    ...[
      ...KOTLIN_VALUE_IMPORTS,
      "androidx.compose.animation.core.Easing",
      "androidx.compose.runtime.Composable",
      "androidx.compose.runtime.ReadOnlyComposable",
      "androidx.compose.ui.unit.Dp",
      "androidx.compose.ui.unit.TextUnit",
    ]
      .sort()
      .map((name) => `import ${name}`),
    "",
    "/** Every color token, for one mode. */",
    "interface Colors {",
  ];
  for (const token of model.colors) {
    if (token.description) lines.push(`    /** ${token.description} */`);
    lines.push(`    val ${property(token.path)}: Color`);
  }
  lines.push(
    "",
    "    /** Every color with its token name, in token order. For screens that list the colors. */",
    "    fun entries(): List<Pair<String, Color>> = listOf(",
  );
  for (const token of model.colors) {
    lines.push(`        "${kebab(token.path)}" to ${property(token.path)},`);
  }
  lines.push("    )", "}");

  if (model.sizes.length > 0) {
    lines.push("", "/** Control sizes, for one input device. */", "class Sizes(");
    for (const token of model.sizes) {
      if (token.description) lines.push(`    /** ${token.description} */`);
      lines.push(`    val ${property(token.path)}: Dp,`);
    }
    lines.push(")");
  }

  for (const [group, tokens] of groups) {
    lines.push("", `/** The \`${group}\` tokens. */`, `class ${kotlinGroupClass(group)}(`);
    for (const token of tokens) {
      if (token.description) lines.push(`    /** ${token.description} */`);
      lines.push(`    val ${kotlinMember(group, token)}: ${kotlinValue(token)[0]},`);
    }
    lines.push(")");
  }

  lines.push(
    "",
    "/** A full set of token values: the colors of both modes, the sizes of both input devices and the shared values. */",
    "class Theme(",
    "    val light: Colors,",
    "    val dark: Colors,",
  );
  if (model.sizes.length > 0) lines.push("    val pointer: Sizes,", "    val touch: Sizes,");
  for (const group of groups.keys()) {
    lines.push(`    val ${camel(group)}: ${kotlinGroupClass(group)},`);
  }
  lines.push(")", "");
  lines.push(
    ...kotlinThemeValue(model, "Default", [
      "The theme the token files describe, which the components draw with unless they are given",
      "another.",
    ]),
  );

  for (const group of groups.keys()) {
    lines.push(
      "",
      `/** The \`${group}\` tokens of the theme in effect. */`,
      `val ${pascal(group)}: ${kotlinGroupClass(group)}`,
      `    @Composable @ReadOnlyComposable get() = LocalTheme.current.${camel(group)}`,
    );
  }

  if (model.icons?.length) {
    lines.push(
      "",
      `/** Icons as SVG path data on a ${ICON_GRID} by ${ICON_GRID} grid, stroked ${ICON_STROKE} wide with round caps and joins. */`,
      "enum class IconName(val paths: List<String>) {",
    );
    for (const icon of model.icons) {
      const paths = icon.paths.map((path) => JSON.stringify(path)).join(", ");
      lines.push(`    ${pascal(icon.name)}(listOf(${paths})),`);
    }
    lines.push("}");
  }
  lines.push("");
  return lines.join("\n");
}

/**
 * A theme as a Kotlin file of its own, for the Compose components: `val <Name>Theme`, which an
 * app passes to the theme composable. Every token is written, so it takes nothing from the
 * theme around it. `tokensPackage` is where the token types are: the library's, or a project's.
 */
export function emitKotlinTheme(
  model: Model,
  options: { name: string; source: string; packageName: string; tokensPackage: string },
): string {
  if (!/^[a-z][a-z0-9-]*$/.test(options.name)) {
    throw new TokenError(
      `a theme name is lowercase letters, digits and hyphens: "${options.name}"`,
    );
  }
  const segment = /^[A-Za-z_][A-Za-z0-9_]*$/;
  for (const name of [options.packageName, options.tokensPackage]) {
    if (!name.split(".").every((part) => segment.test(part))) {
      throw new TokenError(`not a Kotlin package name: "${name}"`);
    }
  }
  const name = pascal(options.name);
  const imports = [
    ...KOTLIN_VALUE_IMPORTS,
    ...kotlinTokenTypes(model).map((type) => `${options.tokensPackage}.${type}`),
  ].sort();
  return [
    `// Generated by xds from ${options.source}. Do not edit.`,
    "",
    `package ${options.packageName}`,
    "",
    ...imports.map((line) => `import ${line}`),
    "",
    ...kotlinThemeValue(model, name, [
      `The ${options.name} theme, from ${options.source}. Give it to the theme composable, around`,
      "the whole app or any part of it.",
    ]),
    "",
  ].join("\n");
}

// ---------------------------------------------------------------- Rust

function rustColor(color: Rgba): string {
  return `Color::rgba(${color.r}, ${color.g}, ${color.b}, ${float(color.a)})`;
}

function rustConst(token: ValueToken): string {
  const name = token.path.join("_").replaceAll("-", "_").toUpperCase();
  const { value } = token;
  switch (value.kind) {
    case "dimension":
      return `pub const ${name}: f32 = ${float(value.px)};`;
    case "duration":
      return `pub const ${name}: Duration = Duration::from_millis(${value.ms});`;
    case "number":
      return `pub const ${name}: f32 = ${float(value.value)};`;
    case "fontWeight":
      return `pub const ${name}: f32 = ${float(value.value)};`;
    case "fontFamily":
      return `pub const ${name}: &[&str] = &[${value.families.map((family) => JSON.stringify(family)).join(", ")}];`;
    case "cubicBezier":
      return `pub const ${name}: CubicBezier = [${value.points.map(float).join(", ")}];`;
    case "shadow": {
      const { color, offsetX, offsetY, blur, spread } = value.shadow;
      return (
        `pub const ${name}: Shadow = Shadow { color: ${rustColor(color)}, ` +
        `offset_x: ${float(offsetX)}, offset_y: ${float(offsetY)}, ` +
        `blur: ${float(blur)}, spread: ${float(spread)} };`
      );
    }
    case "typography": {
      const { sizePx, weight, lineHeight, letterSpacingPx } = value.typography;
      return (
        `pub const ${name}: Typography = Typography { size: ${float(sizePx)}, ` +
        `weight: ${float(weight)}, line_height: ${float(lineHeight)}, ` +
        `letter_spacing: ${float(letterSpacingPx)} };`
      );
    }
  }
}

/**
 * Plain constants with no UI-framework types, so the crate stays dependency-free. The module is
 * declared with `#[rustfmt::skip]`, so the layout here does not have to match rustfmt's.
 */
function iconSvg(icon: Icon, fill: "none" | "currentColor"): string {
  const paths = icon.paths.map((path) => `<path d="${path}"/>`).join("");
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${ICON_GRID} ${ICON_GRID}" fill="${fill}" ` +
    `stroke="currentColor" stroke-width="${ICON_STROKE}" stroke-linecap="round" ` +
    `stroke-linejoin="round">${paths}</svg>`
  );
}

export function emitRust(model: Model): string {
  const field = (token: { path: string[] }) => token.path.join("_").replaceAll("-", "_");
  const lines = [
    `// ${HEADER}`,
    "",
    "use std::time::Duration;",
    "",
    "use crate::{Color, CubicBezier, Shadow, Typography};",
    "",
    "/// Every color token, for one mode.",
    "#[derive(Debug, Clone, Copy, PartialEq)]",
    "pub struct Colors {",
  ];
  for (const token of model.colors) {
    if (token.description) lines.push(`    /// ${token.description}`);
    lines.push(`    pub ${field(token)}: Color,`);
  }
  lines.push(
    "}",
    "",
    "impl Colors {",
    "    /// Every color with its token name, in token order. For screens that list the colors.",
    `    pub const fn entries(&self) -> [(&'static str, Color); ${model.colors.length}] {`,
    "        [",
  );
  for (const token of model.colors) {
    lines.push(`            ("${kebab(token.path)}", self.${field(token)}),`);
  }
  lines.push("        ]", "    }", "}");
  for (const mode of ["light", "dark"] as const) {
    lines.push("", `pub const ${mode.toUpperCase()}: Colors = Colors {`);
    for (const token of model.colors) {
      lines.push(`    ${field(token)}: ${rustColor(token[mode])},`);
    }
    lines.push("};");
  }
  let group: string | undefined;
  for (const token of model.values) {
    const tokenGroup = token.path.slice(0, -1).join(".");
    if (tokenGroup !== group) lines.push("");
    group = tokenGroup;
    if (token.description) lines.push(`/// ${token.description}`);
    lines.push(rustConst(token));
  }
  if (model.sizes.length > 0) {
    lines.push(
      "",
      "/// Control sizes, for one input device.",
      "#[derive(Debug, Clone, Copy, PartialEq)]",
      "pub struct Sizes {",
    );
    for (const token of model.sizes) {
      if (token.description) lines.push(`    /// ${token.description}`);
      lines.push(`    pub ${field(token)}: f32,`);
    }
    lines.push("}");
    for (const mode of INPUT_MODES) {
      lines.push("", `pub const ${mode.toUpperCase()}: Sizes = Sizes {`);
      for (const token of model.sizes) {
        lines.push(`    ${field(token)}: ${float(token[mode])},`);
      }
      lines.push("};");
    }
  }
  if (model.icons?.length) {
    lines.push(
      "",
      "/// The icons of the design system. `name` is the icon's file name in design/icons.",
      "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
      "pub enum Icon {",
      ...model.icons.map((icon) => `    ${pascal(icon.name)},`),
      "}",
      "",
      "impl Icon {",
      `    pub const ALL: [Icon; ${model.icons.length}] = [`,
      ...model.icons.map((icon) => `        Icon::${pascal(icon.name)},`),
      "    ];",
      "",
      "    pub const fn name(self) -> &'static str {",
      "        match self {",
      ...model.icons.map((icon) => `            Icon::${pascal(icon.name)} => "${icon.name}",`),
      "        }",
      "    }",
      "",
      "    /// The icon as an SVG document, stroked in `currentColor`.",
      "    pub const fn svg(self) -> &'static str {",
      "        match self {",
      ...model.icons.map(
        (icon) => `            Icon::${pascal(icon.name)} => r#"${iconSvg(icon, "none")}"#,`,
      ),
      "        }",
      "    }",
      "",
      "    /// The same drawing with its shapes filled, for a selected state.",
      "    pub const fn filled_svg(self) -> &'static str {",
      "        match self {",
      ...model.icons.map(
        (icon) =>
          `            Icon::${pascal(icon.name)} => r#"${iconSvg(icon, "currentColor")}"#,`,
      ),
      "        }",
      "    }",
      "}",
    );
  }
  lines.push("");
  return lines.join("\n");
}

// ---------------------------------------------------------------- Dart

function dartString(value: string): string {
  return JSON.stringify(value).replaceAll("$", "\\$");
}

function dartValue(token: ValueToken): [type: string, value: string] {
  const { value } = token;
  switch (value.kind) {
    case "dimension":
      return ["double", String(value.px)];
    case "duration":
      return ["Duration", `Duration(milliseconds: ${value.ms})`];
    case "number":
      return ["double", String(value.value)];
    case "fontWeight":
      return ["FontWeight", `FontWeight(${value.value})`];
    case "fontFamily":
      return ["List<String>", `[${value.families.map(dartString).join(", ")}]`];
    case "cubicBezier":
      return ["Cubic", `Cubic(${value.points.join(", ")})`];
    case "shadow": {
      const { color, offsetX, offsetY, blur, spread } = value.shadow;
      return [
        "ShadowToken",
        `ShadowToken(color: ${argbColor(color)}, offsetX: ${offsetX}, offsetY: ${offsetY}, blur: ${blur}, spread: ${spread})`,
      ];
    }
    case "typography": {
      const { sizePx, weight: w, lineHeight, letterSpacingPx } = value.typography;
      // The same whole-pixel line height as React Native and Compose, centered in the line as
      // CSS does: Flutter's default puts the extra space by the font's ascent and descent.
      const line = Math.round(sizePx * lineHeight);
      return [
        "TextStyle",
        `TextStyle(fontSize: ${sizePx}, height: ${line} / ${sizePx}, fontWeight: FontWeight(${w}), ` +
          `letterSpacing: ${letterSpacingPx}, leadingDistribution: TextLeadingDistribution.even)`,
      ];
    }
  }
}

export function emitDart(model: Model): string {
  const property = (path: string[]) => camel(kebab(path));
  const lines = [
    `// ${HEADER}`,
    "// dart format off",
    "// ignore_for_file: constant_identifier_names",
    "",
    "import 'package:flutter/animation.dart';",
    "import 'package:flutter/painting.dart';",
    "",
    "import 'types.dart';",
    "",
    "/// Every color token, for one mode.",
    "final class ColorTokens {",
    "  const ColorTokens({",
  ];
  for (const token of model.colors) lines.push(`    required this.${property(token.path)},`);
  lines.push("  });", "");
  for (const token of model.colors) {
    if (token.description) lines.push(`  /// ${token.description}`);
    lines.push(`  final Color ${property(token.path)};`);
  }
  lines.push(
    "",
    "  /// Every color with its token name, in token order. For screens that list the colors.",
    "  List<(String, Color)> get entries => [",
  );
  for (const token of model.colors)
    lines.push(`    ('${kebab(token.path)}', ${property(token.path)}),`);
  lines.push("  ];");
  for (const mode of ["light", "dark"] as const) {
    lines.push("", `  static const ${mode} = ColorTokens(`);
    for (const token of model.colors) {
      lines.push(`    ${property(token.path)}: ${argbColor(token[mode])},`);
    }
    lines.push("  );");
  }
  lines.push("}");

  const groups = new Map<string, ValueToken[]>();
  for (const token of model.values) {
    const group = token.path[0] as string;
    groups.set(group, [...(groups.get(group) ?? []), token]);
  }
  for (const [group, tokens] of groups) {
    lines.push("", `abstract final class ${pascal(group)}Tokens {`);
    for (const token of tokens) {
      const name = property(token.path.slice(1));
      const [type, value] = dartValue(token);
      if (token.description) lines.push(`  /// ${token.description}`);
      lines.push(
        `  static const ${type} ${/^[0-9]/.test(name) ? group.charAt(0) + name : name} = ${value};`,
      );
    }
    lines.push("}");
  }

  if (model.sizes.length > 0) {
    lines.push(
      "",
      "/// Control sizes, for one input device.",
      "final class SizeTokens {",
      "  const SizeTokens({",
    );
    for (const token of model.sizes) lines.push(`    required this.${property(token.path)},`);
    lines.push("  });", "");
    for (const token of model.sizes) {
      if (token.description) lines.push(`  /// ${token.description}`);
      lines.push(`  final double ${property(token.path)};`);
    }
    for (const mode of INPUT_MODES) {
      lines.push("", `  static const ${mode} = SizeTokens(`);
      for (const token of model.sizes) lines.push(`    ${property(token.path)}: ${token[mode]},`);
      lines.push("  );");
    }
    lines.push("}");
  }
  const icons = model.icons ?? [];
  if (icons.length > 0) {
    lines.push(
      "",
      `/// Icons as SVG path data on a ${ICON_GRID} by ${ICON_GRID} grid, stroked ${ICON_STROKE} wide with round caps and joins.`,
      "enum IconName {",
    );
    icons.forEach((icon, index) => {
      const paths = icon.paths.map((p) => `'${p}'`).join(", ");
      const end = index === icons.length - 1 ? ";" : ",";
      lines.push(`  ${camel(icon.name)}([${paths}])${end}`);
    });
    lines.push("", "  const IconName(this.paths);", "", "  final List<String> paths;", "}");
  }
  lines.push("");
  return lines.join("\n");
}
