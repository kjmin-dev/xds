async function page(
  path: string,
  frontmatter: { title: string; description?: string; order?: number },
  body: string,
) {
  const file = join(content, path);
  await mkdir(join(file, ".."), { recursive: true });
  const lines = [`title: ${JSON.stringify(frontmatter.title)}`];
  if (frontmatter.description)
    lines.push(`description: ${JSON.stringify(frontmatter.description)}`);
  if (frontmatter.order !== undefined) lines.push(`sidebar:\n  order: ${frontmatter.order}`);
  await writeFile(file, `---\n${lines.join("\n")}\n---\n\n${body.trim()}\n`);
}

// ---------------------------------------------------------------- guides

type Section = { title: string; body: string };

/** The text before the first `## ` heading, and one entry per `## ` section. */
function sections(markdown: string): { intro: string; sections: Section[] } {
  const [head = "", ...rest] = markdown.split(/^## /m);
  return {
    intro: head.replace(/^# .*\n/, "").trim(),
    sections: rest.map((part) => {
      const newline = part.indexOf("\n");
      return { title: part.slice(0, newline).trim(), body: part.slice(newline + 1).trim() };
    }),
  };
}

/** A section as a page of its own: its `###` headings become the page's `##`. */
const promote = (body: string) => body.replace(/^###/gm, "##");
/** Several sections on one page keep their headings. */
const join2 = (parts: Section[]) => parts.map((s) => `## ${s.title}\n\n${s.body}`).join("\n\n");

type Plan = {
  path: string;
  title: string;
  description: string;
  /** Section titles from the source, in order. One section is promoted; several are joined. */
  take: string[];
  intro?: boolean;
};

async function guide(source: string, directory: string, plan: Plan[], links: [RegExp, string][]) {
  const parsed = sections(await readFile(join(root, source), "utf8"));
  const used = new Set<string>();
  for (const [index, entry] of plan.entries()) {
    const parts = entry.take.map((title) => {
      const section = parsed.sections.find((s) => s.title === title);
      if (!section) throw new Error(`${source} has no "## ${title}" section`);
      used.add(title);
      return section;
    });
    const [first] = parts;
    let body = parts.length === 1 && first ? promote(first.body) : join2(parts);
    if (entry.intro) body = `${parsed.intro}\n\n${body}`;
    for (const [pattern, replacement] of links) body = body.replace(pattern, replacement);
    await page(
      `${directory}/${entry.path}.md`,
      { title: entry.title, description: entry.description, order: index + 1 },
      body,
    );
  }
  // A section added to the source has to be given a page, not silently dropped.
  const missed = parsed.sections.filter((s) => !used.has(s.title)).map((s) => s.title);
  if (missed.length > 0) {
    throw new Error(`${source}: no page takes the section(s) ${missed.join(", ")}`);
  }
}

// ---------------------------------------------------------------- tokens

const hex = ({ r, g, b, a }: Rgba) => {
  const channels = [r, g, b].map((c) => Math.round(c).toString(16).padStart(2, "0")).join("");
  return a === 1 ? `#${channels}` : `#${channels} at ${Math.round(a * 100)}%`;
};
const css = ({ r, g, b, a }: Rgba) => `rgb(${r} ${g} ${b} / ${a})`;
const swatch = (color: Rgba) =>
  `<span class="swatch" style="background:${css(color)}"></span>\`${hex(color)}\``;
const cell = (text?: string) => (text ?? "").replaceAll("|", "\\|");

function table(header: string[], rows: string[][]): string {
  return [
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
}

const colorTable = (tokens: ColorToken[]) =>
  table(
    ["Token", "Light", "Dark", "Use"],
    tokens.map((token) => [
      `\`${token.path.join(".")}\``,
      swatch(token.light),
      swatch(token.dark),
      cell(token.description),
    ]),
  );

function show(value: Value): string {
  switch (value.kind) {
    case "dimension":
      return `${value.px}px`;
    case "duration":
      return `${value.ms}ms`;
    case "number":
    case "fontWeight":
      return String(value.value);
    case "fontFamily":
      return value.families.join(", ");
    case "cubicBezier":
      return `cubic-bezier(${value.points.join(", ")})`;
    case "shadow": {
      const { offsetX, offsetY, blur, spread, color } = value.shadow;
      return `${offsetX}px ${offsetY}px ${blur}px ${spread}px, ${hex(color)}`;
    }
    case "typography": {
      const { sizePx, weight, lineHeight, letterSpacingPx } = value.typography;
      return `${sizePx}px / ${lineHeight} / ${weight}, tracking ${letterSpacingPx}px`;
    }
  }
}

const SEMANTIC = ["background", "text", "border", "accent", "control", "danger", "status"];
const title = (name: string) => name.charAt(0).toUpperCase() + name.slice(1).replaceAll("-", " ");

async function tokens() {
  const tokensDir = join(root, "design/tokens");
  const model = await loadModel(tokensDir);
  const groups = new Map<string, ColorToken[]>();
  for (const token of model.colors) {
    const group = token.path[0] ?? "";
    groups.set(group, [...(groups.get(group) ?? []), token]);
  }
  const semantic = SEMANTIC.filter((name) => groups.has(name));
  const component = [...groups.keys()].filter((name) => !SEMANTIC.includes(name));

  await page(
    "tokens/colors.mdx",
    {
      title: "Colors",
      description: "Every semantic and component color token, with its light and dark value.",
      order: 1,
    },
    [
      NOTE("design/tokens"),
      "Screens and components use the semantic colors. The component colors belong to one component each, on every platform. The raw palette is not listed: nothing outside the token files refers to it.",
      "## Semantic colors",
      ...semantic.map((name) => `### ${title(name)}\n\n${colorTable(groups.get(name) ?? [])}`),
      "## Component colors",
      ...component.map((name) => `### ${title(name)}\n\n${colorTable(groups.get(name) ?? [])}`),
    ].join("\n\n"),
  );

  const values = (prefix: string) =>
    model.values
      .filter((token) => token.path[0] === prefix)
      .map((token) => [`\`${token.path.join(".")}\``, show(token.value), cell(token.description)]);
  const valueTable = (prefix: string) => table(["Token", "Value", "Use"], values(prefix));

  await page(
    "tokens/typography.mdx",
    {
      title: "Typography",
      description: "The type roles and the font tokens they are built from.",
      order: 2,
    },
    [
      NOTE("design/tokens/base.json"),
      "Screens pick a role, never a raw size. A role is written as size / line height / weight.",
      "## Roles",
      valueTable("typography"),
      "## Font",
      valueTable("font"),
    ].join("\n\n"),
  );

  await page(
    "tokens/sizes.mdx",
    {
      title: "Sizes and space",
      description: "Control sizes for pointer and touch input, spacing, radius, borders and focus.",
      order: 3,
    },
    [
      NOTE("design/tokens"),
      "## Control sizes",
      "Sizes depend on the input device, not on the width of the screen.",
      table(
        ["Token", "Pointer", "Touch", "Use"],
        model.sizes.map((token) => [
          `\`size.${token.path.join(".")}\``,
          `${token.pointer}px`,
          `${token.touch}px`,
          cell(token.description),
        ]),
      ),
      "## Space",
      valueTable("space"),
      "## Radius",
      valueTable("radius"),
      "## Border and focus",
      table(["Token", "Value", "Use"], [...values("border"), ...values("focus")]),
    ].join("\n\n"),
  );

  await page(
    "tokens/motion-and-shadow.mdx",
    {
      title: "Motion and shadow",
      description: "Durations, easing curves, the press scale and the three shadows.",
      order: 4,
    },
    [
      NOTE("design/tokens/base.json"),
      "## Motion",
      valueTable("motion"),
      "## Shadow",
      "A shadow is written as offset x, offset y, blur, spread, then its color.",
      valueTable("shadow"),
    ].join("\n\n"),
  );

  // Themes: each one resolved through the same semantic tokens, without applying it.
  // The default first, then the rest by name.
  const themes = (await listThemes(root)).sort(
    (a, b) =>
      Number(b.name === "indigo") - Number(a.name === "indigo") || a.name.localeCompare(b.name),
  );
  const parts: string[] = [
    NOTE("design/themes"),
    "A theme is an accent ramp and a neutral ramp. The semantic colors refer to the palette by step, so swapping the two ramps recolors everything. Every theme passes every contrast check, because each step has the same relative luminance as the same step of `indigo`.",
    "Apply one with `xds theme <name>` in a project, or `mise run theme <name>` in this repository.",
  ];
  for (const theme of themes) {
    const themed = await loadModel(tokensDir, join(root, "design/themes", `${theme.name}.json`));
    const color = (path: string, mode: "light" | "dark") => {
      const token = themed.colors.find((t) => t.path.join(".") === path);
      if (!token) throw new Error(`no color token ${path}`);
      return css(token[mode]);
    };
    const ramp = (group: Record<string, unknown>) =>
      `<div class="ramp">${Object.entries(group)
        .filter(([step]) => !step.startsWith("$"))
        .map(([step, token]) => {
          const value = (token as { $value: { hex: string } }).$value.hex;
          return `<span title="${step}: ${value}" style="background:${value}"></span>`;
        })
        .join("")}</div>`;
    const sample = (mode: "light" | "dark") =>
      `<div style="background:${color("background.base", mode)};color:${color("text.primary", mode)}"><strong>${mode === "light" ? "Light" : "Dark"}</strong><span style="color:${color("text.secondary", mode)}">Secondary text</span><span style="color:${color("text.accent", mode)}">A link</span><span class="button" style="background:${color("button.primary.background", mode)};color:${color("button.primary.text", mode)}">Primary</span></div>`;
    parts.push(
      `## ${theme.name}`,
      theme.description,
      `<div class="theme-sample not-content">${sample("light")}${sample("dark")}</div>`,
      "Accent",
      ramp(theme.palette.accent),
      "Neutral",
      ramp(theme.palette.neutral),
    );
  }
  await page(
    "tokens/themes.mdx",
    {
      title: "Themes",
      description: "The five color themes that ship with the template.",
      order: 5,
    },
    parts.join("\n\n"),
  );
}

